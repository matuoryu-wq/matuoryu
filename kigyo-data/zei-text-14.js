- ミス（過少申告）なら：過少申告加算税10%（一定の部分は15%）、更正できる期間は原則5年、延滞税の除外特例あり、通常は刑事事件にならない
- 隠蔽・仮装なら：重加算税35%、更正できる期間は7年、延滞税の除外特例なし、悪質なら脱税として告発されることもある
