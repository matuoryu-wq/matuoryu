- 株主グループを持株割合の大きい順に並べ、上位3位までで初めて50%を超えるときに、本人の属するグループがその中に含まれる
- 本人の属するグループの持株割合が10%を超える
- 本人（配偶者などを含む）の持株割合が5%を超える

