- 対象外：健康診断・人間ドック（重大な病気が見つかって治療した場合は対象）、美容整形、ビタミン剤・健康食品、自家用車のガソリン代・駐車場代、本人の希望による差額ベッド代、見た目のための大人の歯列矯正

